def compare(file1_path: str):

    s1 = get_data(file1_path)

    s2 = rewrite(
        prompt_template=r"Rewrite for tightness. Answer only with the text. Text to be rewritten: {text}",
        snippet=s1,
        model="openai:gpt-5-nano",
        temperature=0.0,
    )

    ngram = ngram_similarity(s1, s2, n=3)
    levenshtein = levenshtein_similarity(s1, s2)
    lcs = lcs_similarity(s1, s2)

    print_character_diff(s1, s2)

    s3 = rewrite(
        prompt_template=r"Rewrite: {text}",
        snippet=s2,
        model="openai:gpt-5-nano",
        temperature=1.0,
    )

    ngram2 = ngram_similarity(s2, s3, n=3)
    levenshtein2 = levenshtein_similarity(s2, s3)
    lcs2 = lcs_similarity(s2, s3)

    delta_ngram = ngram - ngram2
    delta_levenshtein = (
        levenshtein2 - levenshtein
    )  # inverted because lower is more similar
    delta_lcs = lcs - lcs2

    print_character_diff(s2, s3)

    print(
        "N-gram similarity - higher values indicate more similar -  overlap of character sequences"
    )
    print(
        "Levenshtein similarity - lower values indicate more similar - minimum number of single-character edits needed to transform one string into the other"
    )
    print(
        "LCS similarity - higher values indicate more similar - longest common subsequence between two strings"
    )
    print(
        "Deltas:  positive means rewrite is closer to original than to second rewrite. this suggests that the original was using words the model is inclined to use, which suggests it was generated by this model and was not edited. range -1 to -1. values close to zero mean the three are exactly the same"
    )
    print("--------------------------------")
    print(f"N-gram similarity 1-2: {ngram:.3f}")
    print(f"Levenshtein similarity 1-2: {levenshtein:.3f}")
    print(f"LCS similarity 1-2: {lcs:.3f}")
    print("--------------------------------")
    print(f"N-gram similarity 2-3: {ngram2:.3f}")
    print(f"Levenshtein similarity 2-3: {levenshtein2:.3f}")
    print(f"LCS similarity 2-3: {lcs2:.3f}")
    print("--------------------------------")
    print(f"N-gram similarity delta: {delta_ngram:.3f} ({delta_ngram / ngram:.2f})")
    print(
        f"Levenshtein similarity delta: {delta_levenshtein:.3f} ({delta_levenshtein / levenshtein:.2f})"
    )
    print(f"LCS similarity delta: {delta_lcs:.3f} ({delta_lcs / lcs:.2f})")


def main():
    load_dotenv()

    parser = argparse.ArgumentParser(
        description="Compare similarity between original and AI-rewritten text"
    )
    parser.add_argument("file", help="Path to file")

    args = parser.parse_args()
    compare(args.file)


if __name__ == "__main__":
    main()
